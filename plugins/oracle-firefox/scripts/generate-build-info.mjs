import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(root, "src");
const meta = JSON.parse(await readFile(path.join(root, "plugin.meta.json"), "utf8"));
const sourceFiles = (await readdir(sourceRoot))
  .filter((name) => name.endsWith(".mjs") && name !== "generated-build-info.mjs")
  .sort();
const digest = createHash("sha256");
for (const name of sourceFiles) {
  digest.update(name).update("\0").update(await readFile(path.join(sourceRoot, name))).update("\0");
}
const sourceDigest = digest.digest("hex");
const build = {
  packageVersion: meta.version,
  protocolVersion: meta.protocolVersion,
  schemaVersion: meta.schemaVersion,
  releaseSequence: meta.releaseSequence,
  sourceDigest,
  buildId: `oracle-firefox-${meta.version}-${sourceDigest.slice(0, 16)}`,
};
await writeFile(
  path.join(sourceRoot, "generated-build-info.mjs"),
  `// Generated by scripts/generate-build-info.mjs.\nexport const GENERATED_BUILD_INFO = Object.freeze(${JSON.stringify(build, null, 2)});\n`,
);
await writeFile(path.join(root, "build-manifest.json"), `${JSON.stringify(build, null, 2)}\n`);
